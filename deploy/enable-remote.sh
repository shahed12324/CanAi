#!/usr/bin/env bash
# Let ONE external host (e.g. your cPanel server) use this VPS's database and AI engine.
#   sudo ./deploy/enable-remote.sh --allow-ip 203.0.113.10 --domain jarvis.example.com
# - PostgreSQL gets TLS (self-signed certificate) and is published on :5432, firewalled to that IP only.
# - nginx exposes the AI engine at https://<domain>/engine/ for that IP only (requests are HMAC+JWT signed anyway).
# Re-run with another IP to change the allowed host (the old rule is NOT removed: `ufw delete` it yourself).
set -Eeuo pipefail
ALLOW_IP=""; DOMAIN=""
while [ $# -gt 0 ]; do case "$1" in --allow-ip) ALLOW_IP="${2:-}"; shift 2;; --domain) DOMAIN="${2:-}"; shift 2;; *) echo "unknown option $1" >&2; exit 2;; esac; done
[ "$(id -u)" -eq 0 ] || { echo "run as root" >&2; exit 1; }
[[ "$ALLOW_IP" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}$ ]] || { echo "--allow-ip must be an IPv4 address" >&2; exit 2; }
[[ "$DOMAIN" =~ ^[A-Za-z0-9.-]+$ ]] || { echo "--domain required" >&2; exit 2; }
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"; cd "$ROOT"

mkdir -p infra/pg-certs
if [ ! -f infra/pg-certs/server.key ]; then
  openssl req -new -x509 -days 3650 -nodes -subj "/CN=$DOMAIN" -keyout infra/pg-certs/server.key -out infra/pg-certs/server.crt
fi
chown 999:999 infra/pg-certs/server.key infra/pg-certs/server.crt; chmod 600 infra/pg-certs/server.key; chmod 644 infra/pg-certs/server.crt

cat > infra/docker-compose.remote.yml <<'YML'
# Generated by deploy/enable-remote.sh - PostgreSQL with TLS, published for the allow-listed host.
services:
  postgres:
    command: ["postgres", "-c", "max_connections=300", "-c", "ssl=on", "-c", "ssl_cert_file=/certs/server.crt", "-c", "ssl_key_file=/certs/server.key"]
    volumes:
      - pgdata:/var/lib/postgresql
      - ./pg-certs:/certs:ro
    ports: !override
      - "0.0.0.0:5432:5432"
YML
docker compose -f infra/docker-compose.yml -f infra/docker-compose.remote.yml --env-file .env up -d postgres

if command -v ufw >/dev/null; then
  ufw allow from "$ALLOW_IP" to any port 5432 proto tcp
  ufw allow from "$ALLOW_IP" to any port 443 proto tcp
  ufw allow from "$ALLOW_IP" to any port 80 proto tcp
  ufw deny 5432/tcp || true
else
  echo "WARNING: ufw not installed - port 5432 is open to the internet! Install a firewall that limits it to $ALLOW_IP." >&2
fi

cat > /etc/nginx/snippets/jarvis-engine.conf <<NGX
# AI engine for the allow-listed external web host (generated by enable-remote.sh)
location /engine/ {
    allow $ALLOW_IP;
    deny all;
    rewrite ^/engine/(.*)\$ /\$1 break;
    proxy_pass http://127.0.0.1:8000;
    proxy_http_version 1.1;
    proxy_buffering off;
    proxy_read_timeout 300s;
    proxy_set_header Host \$host;
}
NGX
SITE=/etc/nginx/sites-available/jarvis
grep -q 'snippets/jarvis-engine.conf' "$SITE" || sed -i '0,/location \/ {/s##include snippets/jarvis-engine.conf;\n\n    location / {#' "$SITE"
nginx -t && systemctl reload nginx
cat <<DONE

Done. Put this in the cPanel app's .env:
  DB_HOST=$DOMAIN        DB_PORT=5432     DB_DATABASE=jarvis     DB_SSLMODE=require
  DB_USERNAME=jarvis_app DB_PASSWORD=<DB_APP_PASSWORD from $ROOT/.env>
  DB_ADMIN_USERNAME=jarvis_admin_login   DB_ADMIN_PASSWORD=<DB_ADMIN_PASSWORD>
  AI_ENGINE_URL=https://$DOMAIN/engine   (the VPS needs HTTPS for this: re-run install-vps.sh with --domain/--email first)
  AI_ENGINE_HMAC_SECRET / AI_ENGINE_JWT_SECRET / AI_VAULT_KEY_1  <- copy the SAME values from $ROOT/.env
DONE
